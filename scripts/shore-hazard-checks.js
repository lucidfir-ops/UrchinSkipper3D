import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';

export async function shoreHazardChecks(browser) {
  const engine = browser.browserType().name(),
    page = await browser.newPage({ viewport: { width: 1280, height: 800 }, hasTouch: true }),
    errors = [],
    records = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const action = (id) => page.locator(`[data-action="${id}"]`).click();
  const screen = (name) => page.waitForFunction((name) => urchinDebug.ui.screen === name, name);
  const shot = (label) => page.screenshot({ path: `test-results/shore-${engine}-${label}.png` });
  try {
    await page.goto(process.env.URCHIN_TEST_URL || 'http://127.0.0.1:5180/');
    await page.locator('[data-touch-options]').click();
    await page.locator('[data-action="touchscreen"]').click();
    await page.locator('.screen-back').click();
    await page.locator('#keyboardFallback').click();
    await screen('intro');
    await page.locator('[data-choice-index="1"]').click();
    await screen('starter');
    await action('starter-basic');
    await action('buy-selected');
    await screen('purchase');
    await action('confirm-purchase');
    await screen('harbour');
    await action('chart');
    await page.locator('#playtest [data-choice-index="0"]').click();
    await screen('departure');
    assert.match(await page.locator('.map-caption').textContent(), /Pink ×.*uncharted/);
    await shot('departure-chart');
    await action('sail');
    await screen(null);
    await page.waitForFunction(() => urchinDebug.world.rocks?.length === 40);
    // Test-only weather/position staging; all geometry and logs are generated by the game.
    await page.evaluate(() => {
      const w = urchinDebug.world;
      w.career.sandbox = true;
      w.career.testConditions = { freezeClock: true, weather: 'calm' };
      w.day.minute = 600;
      w.career.assists.groundDots = false;
      w.career.assists.currentOverlay = false;
      w.traffic = { actors: [], nextSpawn: Infinity };
      w.boat.throttle = w.boat.rudder = w.boat.vx = w.boat.vy = 0;
      urchinDebug.step(0.05);
      // An uncharted rock with a safely navigable inspection point beside it.
      const choices = w.rocks
        .filter((r) => !r.charted)
        .flatMap((r) =>
          Array.from({ length: 16 }, (_, i) => {
            const a = (i * Math.PI) / 8,
              x = r.x + Math.cos(a) * 12,
              y = r.y + Math.sin(a) * 12;
            const wet = [
              [0, 0],
              [-3, -6],
              [3, -6],
              [-3, 6],
              [3, 6],
            ].every(([dx, dy]) => urchinDebug.depthAt(x + dx, y + dy) > 3);
            return {
              r,
              x,
              y,
              wet,
              count: w.logs.filter((l) => Math.hypot(l.x - x, l.y - y) < 60).length,
            };
          }),
        )
        .filter((p) => p.wet)
        .sort((a, b) => b.count - a.count);
      const at = choices[0];
      if (!at) throw new Error('No clear inspection point');
      Object.assign(w.boat, { x: at.x, y: at.y, heading: 0 });
      window.shoreInspection = at;
      urchinDebug.terrainView.scene.cameras.main.setZoom(0.85);
    });
    for (const [kind, night, expected] of [
      ['calm', false, 72],
      ['fog', false, 360],
      ['fog', true, 720],
    ]) {
      await page.evaluate(
        ({ kind, night }) => {
          const w = urchinDebug.world;
          w.career.testConditions.weather = kind;
          w.day.minute = night ? 1200 : 600;
          Object.assign(w.boat, {
            x: window.shoreInspection.x,
            y: window.shoreInspection.y,
            vx: 0,
            vy: 0,
            throttle: 0,
          });
          urchinDebug.resetRenderSamples();
        },
        { kind, night },
      );
      await page.waitForFunction((n) => urchinDebug.world.logs.length >= n, expected);
      await page.waitForTimeout(600);
      const sample = await page.evaluate(() => ({
        logs: urchinDebug.world.logs.length,
        fieldLogs: urchinDebug.world.logs.filter((l) =>
          /^(coastal-log|fog-coastal-log|night-coastal-log)-/.test(l.id),
        ).length,
        rocks: urchinDebug.world.rocks.length,
        charted: urchinDebug.world.rocks.filter((r) => r.charted).length,
        weather: urchinDebug.world.weather,
        nearby: urchinDebug.world.logs.filter(
          (l) => Math.hypot(l.x - urchinDebug.world.boat.x, l.y - urchinDebug.world.boat.y) < 60,
        ).length,
      }));
      assert.equal(sample.fieldLogs, expected);
      assert.equal(sample.charted, 30);
      records.push(sample);
      await shot(night ? 'night-fog' : kind);
    }
    // Move into the existing dense timber field to inspect its actual night rendering.
    await page.evaluate(() => {
      const w = urchinDebug.world;
      const candidates = w.logs
        .map((l) => ({ x: l.x + 10, y: l.y }))
        .filter((p) =>
          [
            [0, 0],
            [-3, -6],
            [3, -6],
            [-3, 6],
            [3, 6],
          ].every(([x, y]) => urchinDebug.depthAt(p.x + x, p.y + y) > 3),
        );
      candidates.sort(
        (a, b) =>
          w.logs.filter((l) => Math.hypot(l.x - b.x, l.y - b.y) < 16).length -
          w.logs.filter((l) => Math.hypot(l.x - a.x, l.y - a.y) < 16).length,
      );
      Object.assign(w.boat, candidates[0], { vx: 0, vy: 0, throttle: 0 });
      urchinDebug.resetRenderSamples();
    });
    await page.waitForTimeout(1200);
    await shot('night-timber');
    records.push(await page.evaluate(() => ({ renderSamples: urchinDebug.renderSamples })));
    await page.locator('[data-touch="chart"]').click();
    await screen('knowledge');
    await shot('working-chart');
    for (const viewport of [
      { width: 780, height: 360 },
      { width: 1224, height: 816 },
    ]) {
      await page.setViewportSize(viewport);
      await page.waitForTimeout(250);
      assert(await page.locator('.screen-back').isVisible());
      assert.match(await page.locator('.map-caption').textContent(), /clearance.*datum/);
      await shot(`chart-${viewport.width}`);
    }
    await page.locator('.screen-back').click();
    await screen(null);
    await page.waitForTimeout(400);
    await shot('tablet-night');
    await page.setViewportSize({ width: 1280, height: 800 });
    await page.evaluate(() => {
      const w = urchinDebug.world;
      w.career.testConditions.weather = 'calm';
      w.day.minute = 600;
      w.career.assists.currentOverlay = false;
      w.career.assists.pickingLegend = false;
      urchinDebug.step(0.02);
      w.rocks = [2.4, 1.2, -0.2].map((depth, i) => ({
        id: `visual-band-${i}`,
        x: w.boat.x + (i - 1) * 10,
        y: w.boat.y - 7,
        radius: 2.4,
        length: 1,
        heading: 0,
        kind: 'rock',
        charted: false,
        topDepth: depth - w.environment.seaLevel,
        severity: 1.35,
      }));
      w.logs = [];
      urchinDebug.terrainView.scene.cameras.main.setZoom(1.5);
    });
    await page.waitForTimeout(250);
    await shot('deep-shallow-exposed-bands');
    assert.deepEqual(errors, []);
    writeFileSync(
      `test-results/shore-${engine}.json`,
      JSON.stringify({ errors, records }, null, 2),
    );
    console.log(
      `${engine}: shoreline rocks/charts, 72/360/720 logs, day/fog/night and compact layouts passed`,
    );
  } finally {
    await page.close();
  }
}
